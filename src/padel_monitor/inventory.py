def build_platform_coverage_matrix(
    clubs: list[dict[str, Any]] | None = None,
    platforms: list[dict[str, Any]] | None = None,
) -> list[dict[str, Any]]:
    """Aggregate County Dublin & Greater Dublin club/court coverage per booking platform."""
    clubs = clubs if clubs is not None else VERIFIED_CLUBS
    platforms = platforms if platforms is not None else BOOKING_PLATFORMS

    active_dublin = [
        c for c in clubs if c["in_county_dublin"] == 1 and c["inventory_cohort"] in ("baseline_24_dublin", "newly_verified_dublin")
    ]
    total_dublin_courts = sum(c["verified_padel_courts"] or 0 for c in active_dublin) or 1

    matrix: list[dict[str, Any]] = []
    for p in sorted(platforms, key=lambda x: x["priority_rank"] or 99):
        pid = p["platform_id"]
        dub_clubs = [c for c in active_dublin if c["platform_id"] == pid]
        dub_courts = sum(c["verified_padel_courts"] or 0 for c in dub_clubs)
        pub_dub_courts = sum(
            c["verified_padel_courts"] or 0
            for c in dub_clubs
            if c["access_model"] in ("public_pay_and_play", "hybrid_member_visitor")
        )
        live_meta_clubs = sum(
            1 for c in dub_clubs if c["automated_collection_status"] in ("live_metadata_monitored_slots_need_api", "live_slots_monitored")
        )
        border_clubs = [
            c for c in clubs if c["in_county_dublin"] == 0 and c["platform_id"] == pid
        ]
        border_courts = sum(c["verified_padel_courts"] or 0 for c in border_clubs)

        matrix.append(
            {
                "priority_rank": p["priority_rank"],
                "platform_id": pid,
                "platform_name": p["platform_name"],
                "county_dublin_active_clubs": len(dub_clubs),
                "county_dublin_active_courts": dub_courts,
                "share_of_dublin_courts_pct": round(100.0 * dub_courts / total_dublin_courts, 1),
                "public_or_hybrid_courts_dublin": pub_dub_courts,
                "live_metadata_monitored_clubs": live_meta_clubs,
                "greater_dublin_border_clubs": len(border_clubs),
                "greater_dublin_border_courts": border_courts,
                "official_api_status": p["official_api_status"],
                "public_calendar_auth": p["public_calendar_auth"],
                "automated_slot_access": p["automated_slot_access"],
                "robots_policy_summary": p["robots_policy_summary"],
                "recommended_approach": p["recommended_approach"],
            }
        )
    return matrix
